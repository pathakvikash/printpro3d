// Notifications to the shop owner. The orders route calls notifyNewOrder() and knows
// nothing about how the message is delivered; add WhatsApp/SMS here later.
//
// Email goes through Resend's HTTP API (https://resend.com). Set in .env.local:
//   RESEND_API_KEY=re_...              API key from the Resend dashboard
//   ORDER_NOTIFY_TO=you@example.com    where new-order emails go
//   ORDER_NOTIFY_FROM=PrintPro3D <orders@yourdomain.com>
//       optional; defaults to Resend's test sender, which can only deliver
//       to the address the Resend account was created with
//   SITE_URL=https://yourdomain.com   used for file links in emails (unset: bare file names)
// Without RESEND_API_KEY and ORDER_NOTIFY_TO, notifications are skipped (logged).
// Customer status emails (notifyStatusChange) need only RESEND_API_KEY and the customer's address.

import { describeStatus, type TrackType } from './tracking.ts';

// Links come from SITE_URL, never from the request, so a forged Host header cannot reach the email.
const fileLink = (name: string) => {
  const base = process.env.SITE_URL?.trim().replace(/\/+$/, '');
  return base ? `${base}/api/upload/${encodeURIComponent(name)}` : name;
};

export type OrderLine = {
  kind: 'shop' | 'model';
  qty: number;
  material: string;
  total: number | null; // null = needs a manual quote
  id?: string; // catalogue id, shop lines
  itemName?: string; // shop lines
  file?: string; // model upload name, model lines
  aiPrompt?: string; // model lines generated by AI
};

export type OrderNotice = {
  id: string;
  status: string;
  lines: OrderLine[];
  name: string;
  email: string;
  phone: string;
  address: string;
  notes: string;
  total: number | null; // sum of priced lines, null when none is priced
  unpricedCount: number;
  currency: string;
};

const money = (currency: string, n: number) => `${currency} ${n}`;

function lineText(l: OrderLine, currency: string): string[] {
  const price = l.total === null ? 'needs a manual quote' : money(currency, l.total);
  if (l.kind === 'shop') return [`${l.qty}x ${l.itemName ?? l.id} — ${price}`];
  return [
    `${l.qty}x ${l.material} model ${fileLink(l.file ?? '')} — ${price}`,
    ...(l.aiPrompt ? [`AI-generated from: "${l.aiPrompt.replace(/\s+/g, ' ')}"`] : []),
  ];
}

// Never throws: a failed notification must not fail the order, which is already saved.
export async function notifyNewOrder(order: OrderNotice): Promise<boolean> {
  try {
    const totalText = order.total === null ? 'needs manual quote' : money(order.currency, order.total);
    const pieces = order.lines.reduce((sum, l) => sum + l.qty, 0);
    // customer text on continuation lines is indented, so it cannot pass for an extra field of ours
    const indent = (s: string) => s.replace(/\n/g, '\n    ');
    return await sendEmail(
      `New order: ${order.name} — ${totalText} — ${pieces} piece(s)`,
      [
        `Order ${order.id} (${order.status})`,
        '',
        ...order.lines.flatMap((l) => lineText(l, order.currency)),
        '',
        `Estimated total (priced lines only): ${order.total === null ? 'manual quote needed' : money(order.currency, order.total)}`,
        ...(order.unpricedCount > 0 ? [`${order.unpricedCount} line(s) need a manual quote`] : []),
        '',
        `Customer: ${order.name}`,
        `Email: ${order.email}`,
        `Phone: ${order.phone}`,
        `Address: ${indent(order.address)}`,
        ...(order.notes ? [`Notes: ${indent(order.notes)}`] : []),
      ].join('\n'),
      order.email
    );
  } catch (e) {
    console.error(`Order ${order.id}: notification failed`, e);
    return false;
  }
}

export type RequestNotice = {
  id: string;
  category: string;
  description: string;
  sizeMm: { l: number | null; w: number | null; h: number | null } | null;
  qtyBand: string;
  deliver: string;
  extras: string;
  budget: string;
  images: string[];
  name: string;
  email: string;
  phone: string;
  address: string;
};

// Never throws, same as notifyNewOrder.
export async function notifyNewRequest(r: RequestNotice): Promise<boolean> {
  try {
    const size = r.sizeMm ? `${r.sizeMm.l ?? '?'} × ${r.sizeMm.w ?? '?'} × ${r.sizeMm.h ?? '?'} mm` : 'not given';
    return await sendEmail(
      `New design request: ${r.name} — ${r.category}`,
      [
        `Design request ${r.id}`,
        `Category: ${r.category}`,
        `Quantity: ${r.qtyBand}`,
        `Deliver as: ${r.deliver}`,
        `Approx size: ${size}`,
        ...(r.extras ? [`Moving parts / electronics: ${r.extras}`] : []),
        ...(r.budget ? [`Budget: ${r.budget}`] : []),
        '',
        `Description: ${r.description}`,
        ...r.images.map((n) => `Image: ${fileLink(n)}`),
        '',
        `Customer: ${r.name}`,
        `Email: ${r.email}`,
        `Phone: ${r.phone}`,
        `Address: ${r.address || 'not given'}`,
      ].join('\n'),
      r.email
    );
  } catch (e) {
    console.error(`Request ${r.id}: notification failed`, e);
    return false;
  }
}

async function sendEmail(subject: string, text: string, replyTo: string | undefined, toOverride?: string): Promise<boolean> {
  const key = process.env.RESEND_API_KEY;
  const to = toOverride ?? process.env.ORDER_NOTIFY_TO;
  if (!key || !to) {
    console.warn('Order notification skipped: RESEND_API_KEY / ORDER_NOTIFY_TO not set');
    return false;
  }
  const res = await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
    // plain text only: customer-supplied fields are never interpreted as HTML
    body: JSON.stringify({
      from: process.env.ORDER_NOTIFY_FROM || 'PrintPro3D <onboarding@resend.dev>',
      to,
      ...(replyTo ? { reply_to: replyTo } : {}),
      subject: subject.replace(/\s+/g, ' ').slice(0, 200),
      text,
    }),
    signal: AbortSignal.timeout(5000),
  });
  if (!res.ok) throw new Error(`Resend ${res.status}: ${(await res.text()).slice(0, 300)}`);
  return true;
}

// ---- customer status emails ----

/** Subject and plain-text body for a status change. Pure. SITE_URL gives the link; without it the id is quoted instead. */
export function buildStatusEmail(
  type: TrackType,
  id: string,
  status: string,
  opts: { name?: string; siteUrl?: string } = {}
): { subject: string; text: string } {
  const v = describeStatus(type, status);
  const stage = v.cancelled ? 'Cancelled' : (v.stages[v.current] ?? 'Received');
  const what = type === 'request' ? 'design request' : 'order';
  const base = opts.siteUrl?.trim().replace(/\/+$/, '');
  const name = (opts.name ?? '').replace(/\s+/g, ' ').trim();
  return {
    subject: `Your ${what}: ${stage}`,
    text: [
      name ? `Hello ${name},` : 'Hello,',
      '',
      `Update on your ${what} ${id}`,
      `Stage: ${stage}`,
      v.sentence,
      '',
      base ? `Track it: ${base}/track?id=${encodeURIComponent(id)}` : `Track it on our website with this id: ${id}`,
    ].join('\n'),
  };
}

/** Emails the customer about a new status. Never throws; skips (logged) without RESEND_API_KEY or an address. */
export async function notifyStatusChange(
  type: TrackType,
  id: string,
  status: string,
  customer: { name?: unknown; email?: unknown }
): Promise<boolean> {
  try {
    const email = typeof customer.email === 'string' ? customer.email.trim() : '';
    if (!process.env.RESEND_API_KEY || !email) {
      console.warn(`Status email for ${id} skipped: ${email ? 'RESEND_API_KEY not set' : 'no customer email'}`);
      return false;
    }
    const m = buildStatusEmail(type, id, status, {
      name: typeof customer.name === 'string' ? customer.name : '',
      siteUrl: process.env.SITE_URL,
    });
    return await sendEmail(m.subject, m.text, process.env.ORDER_NOTIFY_TO, email);
  } catch (e) {
    console.error(`${id}: status email failed`, e);
    return false;
  }
}
